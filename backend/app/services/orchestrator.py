"""
Agent Orchestrator — The core brain of Open GrokBot.

Handles the full agent loop: receive message → retrieve context → call LLM →
execute tools → loop until done → broadcast result. Supports both 1:1 and
multi-agent group chat conversations with autonomous handoffs.
"""

import json
import re
import uuid
import logging
import asyncio
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import select
from sqlalchemy.orm import selectinload

from app.config import settings
from app.schemas.input import content_parts, RunOptions
from app.db.session import AsyncSessionLocal
from app.models.bot import Bot
from app.models.conversation import Conversation, ConversationParticipant
from app.models.message import Message
from app.models.task import Task
from app.services.llm_gateway import LLMGateway, generation_options
from app.services.memory import MemoryManager
from app.services.sandbox import SandboxManager
from app.services.tools.registry import ToolRegistry

logger = logging.getLogger(__name__)

# Maximum iterations in the agent loop to prevent runaway execution
MAX_AGENT_ITERATIONS = 25


class AgentOrchestrator:
    """Orchestrates AI agent interactions for conversations.

    For 1:1 chats, routes messages directly to the assigned bot.
    For group chats, determines which bot(s) should respond and
    enables autonomous inter-bot messaging and task handoffs.
    """

    def __init__(self, redis_client=None):
        self.memory = MemoryManager()
        self.registry = ToolRegistry()
        self.redis = redis_client
        self.registry.register_default_tools()
        from app.services.fleet import ModelFleet
        self.fleet = ModelFleet()
        self.fleet.register(self.registry)

    async def process_message(
        self,
        conversation_id: str,
        user_message_content: str,
        sender_type: str = "user",
        sender_bot_id: Optional[str] = None,
        attachments: list | None = None,
        options: dict | None = None,
        goal_id: str | None = None,
    ) -> list[dict]:
        """Main entry point — process an incoming message in a conversation.

        Args:
            conversation_id: UUID of the conversation.
            user_message_content: The text content of the message.
            sender_type: 'user' or 'bot' (for inter-agent messages).
            sender_bot_id: If sender is a bot, its UUID.

        Returns:
            List of response message dicts generated by bot(s).
        """
        from app.services.automation import register_goal_tools
        await register_goal_tools(self.registry, conversation_id, goal_id, AsyncSessionLocal)
        self.options = RunOptions(**(options or {}))
        async with AsyncSessionLocal() as db:
            # Persist the incoming message
            incoming_msg = Message(
                id=str(uuid.uuid4()),
                conversation_id=conversation_id,
                sender_type=sender_type,
                sender_bot_id=sender_bot_id,
                content=user_message_content,
                message_type="text",
                metadata_json={"attachments": attachments or []},
                created_at=datetime.now(timezone.utc).replace(tzinfo=None),
            )
            db.add(incoming_msg)
            await db.commit()

            # Load conversation with participants
            result = await db.execute(
                select(Conversation)
                .options(selectinload(Conversation.participants))
                .where(Conversation.id == conversation_id)
            )
            conversation = result.scalar_one_or_none()

            if not conversation:
                logger.error(f"Conversation {conversation_id} not found")
                return []

            if self.options.output != "text":
                from app.services.media import generate_media
                files = await generate_media(self.options.output, user_message_content, self.options.aspect_ratio, self.options.duration)
                message = await self._save_message(db, conversation_id, "bot", conversation.participants[0].bot_id, "Your image is ready." if self.options.output == "image" else "Your video is ready.", metadata={"attachments": files})
                return [message]

            # Determine responding bots
            participant_bot_ids = [p.bot_id for p in conversation.participants]

            if conversation.is_group:
                return await self._handle_group_chat(
                    db, conversation, participant_bot_ids,
                    user_message_content, sender_type, sender_bot_id,
                )
            else:
                # 1:1 chat — single bot responds
                if not participant_bot_ids:
                    logger.error("No bots in conversation")
                    return []
                bot_id = participant_bot_ids[0]
                return await self._run_agent_loop(
                    db, conversation_id, bot_id, user_message_content
                )

    async def _handle_group_chat(
        self, db, conversation, bot_ids, message, sender_type, sender_bot_id
    ) -> list[dict]:
        """Handle multi-agent group chat with autonomous routing.

        Uses a coordinator LLM call to decide which bot(s) should respond,
        then runs each selected bot's agent loop. Bots can hand off to
        each other by emitting handoff messages.
        """
        bots = (await db.execute(select(Bot).where(Bot.id.in_(bot_ids)).order_by(Bot.created_at))).scalars().all()
        bot_map = {str(bot.id): bot for bot in bots}
        self.team_roster = "\n".join(f"{bot.name}: {bot.role}" for bot in bots)
        coordinator = next((b for b in bots if b.role.casefold() == "coordinator" and b.llm_provider == "openai"), None)
        if coordinator:
            return await self._coordinate_team(db, conversation, bots, coordinator, message)
        all_responses = []
        # Bounded turns, shared DB history, and explicit handoffs between teammates.
        for _round in range(self.options.team_rounds):
            pending = list(bot_map)
            visits = {}
            while pending:
                bot_id = pending.pop(0)
                if visits.get(bot_id, 0) >= 2: continue
                visits[bot_id] = visits.get(bot_id, 0) + 1
                responses = await self._run_agent_loop(db, str(conversation.id), bot_id, message)
                all_responses.extend(responses)
                for response in responses:
                    meta = response.get("metadata") or {}
                    target_name = meta.get("target_bot_name", "").casefold()
                    target_id = next((id for id, bot in bot_map.items() if bot.name.casefold() == target_name), None)
                    if response.get("message_type") == "handoff" and target_id and visits.get(target_id, 0) < 2:
                        pending = [target_id] + [id for id in pending if id != target_id]
        return all_responses

    async def _coordinate_team(self, db, conversation, bots, coordinator, message):
        cid = str(conversation.id)
        self.phase_instructions = "Plan this task briefly. Delegate only work that helps. Choose up to 3 teammates using HANDOFF[exact teammate name: concrete task]. Do not claim the task is done."
        self.internal_activity = True
        self.planning = True
        responses = await self._run_agent_loop(db, cid, coordinator.id, message)
        self.planning = False
        requested = [name.strip().casefold() for response in responses for name in re.findall(r"HANDOFF\[([^:\]]+):", response.get("content", ""))]
        specialists = [b for b in bots if b.id != coordinator.id and b.name.casefold() in requested][:3]
        # No forced specialist turns: simple requests can be answered by the manager.
        self.phase_instructions = "Execute your assigned part using the shared conversation. Read earlier teammates’ findings. Deliver evidence and finished work, and identify anything still blocked."
        for _ in range(self.options.team_rounds):
            for bot in specialists:
                responses.extend(await self._run_agent_loop(db, cid, bot.id, message))
        self.phase_instructions = "The specialist turns have finished. Review their results. Use tools to fix remaining gaps when possible. Give the user the final answer, deliverables, verification, and concrete blockers. Do not emit another HANDOFF. Never turn a failed tool call into a success claim."
        self.internal_activity = False
        responses.extend(await self._run_agent_loop(db, cid, coordinator.id, message))
        self.phase_instructions = ""
        return responses

    async def _run_agent_loop(
        self, db, conversation_id: str, bot_id: str, trigger_message: str
    ) -> list[dict]:
        """Core agent loop for a single bot.

        1. Retrieve conversation context + bot memory
        2. Call LLM with available tools
        3. If LLM returns tool calls → execute them → append results → loop
        4. If LLM returns text → save as bot message → broadcast → done
        5. Detect task completion and update status
        """
        # Load bot configuration
        result = await db.execute(select(Bot).where(Bot.id == bot_id))
        bot = result.scalar_one_or_none()
        if not bot:
            logger.error(f"Bot {bot_id} not found")
            return []

        # Update bot status to working
        bot.status = "working"
        await db.commit()
        await self._broadcast_status(bot_id, "working")

        responses = []

        try:
            # Build system prompt
            system_prompt = self._build_system_prompt(bot)
            system_prompt += "\nYou are the OpenAI manager. Use consult_specialist automatically for focused research, writing, or independent analysis when useful; solve simple tasks yourself. Specialists only advise and cannot perform actions. You own all tool execution, verification, and the final user-facing response. Do not ask the user to choose models or manage handoffs. Never share credentials with specialists. Use generate_image or generate_video only when the user requested media. If a specialist fails, continue yourself and report only blockers that affect the requested result."
            if getattr(self, "phase_instructions", ""):
                system_prompt += "\nCurrent team phase: " + self.phase_instructions
            if getattr(self, "team_roster", None):
                system_prompt += "\nYou are in a team conversation. Read teammates’ messages, challenge errors, and build on prior work. Do not invent actions. To hand off use HANDOFF[exact teammate name: task].\nTeam:\n" + self.team_roster

            history = (await db.execute(select(Message).where(Message.conversation_id == conversation_id, Message.message_type.in_(["text", "handoff"])).order_by(Message.created_at.desc()).limit(40))).scalars().all()
            names = dict((await db.execute(select(Bot.id, Bot.name))).all())
            messages = [{"role": "system", "content": system_prompt}]
            # Re-send the three newest attachment sets, keeping older references readable.
            attachment_ids = [item.id for item in history if (item.metadata_json or {}).get("attachments")][:3]
            for item in reversed(history):
                if item.sender_type == "user":
                    files = (item.metadata_json or {}).get("attachments", [])
                    content = content_parts(item.content, files if item.id in attachment_ids else [])
                    if files and item.id not in attachment_ids:
                        content += "\nEarlier attachment reference (not resent): " + ", ".join(a["name"] for a in files)
                    messages.append({"role": "user", "content": content})
                elif item.sender_bot_id == bot_id:
                    messages.append({"role": "assistant", "content": item.content})
                else:
                    messages.append({"role": "user", "content": f"Teammate {names.get(item.sender_bot_id, 'Agent')}: {item.content}"})

            # Get available tools for this bot
            await self.registry.load_plugins(db, bot)
            tools = [] if getattr(self, "planning", False) else self.registry.get_tools_for_bot(bot)

            # Agent loop
            for iteration in range(getattr(self, "options", RunOptions()).max_iterations):
                logger.info(
                    f"Agent loop iteration {iteration + 1} for bot '{bot.name}'"
                )

                run = getattr(self, "options", RunOptions())
                provider = bot.llm_provider if getattr(self, "team_roster", None) and bot.role.casefold() != "coordinator" else run.provider or bot.llm_provider
                model = bot.llm_model if getattr(self, "team_roster", None) and bot.role.casefold() != "coordinator" else run.model or bot.llm_model
                response = await LLMGateway.complete(
                    messages=messages,
                    tools=tools if tools else None,
                    model=model,
                    provider=provider,
                    **generation_options(run, provider, model),
                )

                reply = response.choices[0].message

                # Handle tool calls
                if reply.tool_calls:
                    # Append assistant message with tool calls
                    messages.append(reply.model_dump())

                    for tool_call in reply.tool_calls:
                        func_name = tool_call.function.name
                        try:
                            args = json.loads(tool_call.function.arguments)
                        except json.JSONDecodeError:
                            args = {}

                        logger.info("Bot %s calling tool %s", bot.id, func_name)

                        # Broadcast tool call status
                        tool_msg = await self._save_message(
                            db, conversation_id, "bot", bot_id,
                            f"Calling tool: {func_name}",
                            message_type="tool_call",
                            metadata={
                                "tool_name": func_name,
                                "arguments": args,
                                "tool_call_id": tool_call.id,
                            },
                        )
                        responses.append(tool_msg)

                        # Execute the tool
                        allowed_names = {t["function"]["name"] for t in tools}
                        if func_name not in allowed_names:
                            tool_result = {"error": "This tool is not enabled for this agent."}
                        else:
                            tool_result = await self.registry.execute_tool(func_name, args, bot_id)
                        generated_files = tool_result.pop("_attachments", [])
                        if generated_files:
                            responses.append(await self._save_message(db, conversation_id, "bot", bot_id, "Generated media", metadata={"attachments": generated_files}))

                        # Save tool result
                        result_msg = await self._save_message(
                            db, conversation_id, "system", None,
                            json.dumps(tool_result, default=str),
                            message_type="tool_result",
                            metadata={
                                "tool_name": func_name,
                                "tool_call_id": tool_call.id,
                            },
                        )
                        responses.append(result_msg)

                        # Append tool result for next LLM call
                        messages.append({
                            "role": "tool",
                            "tool_call_id": tool_call.id,
                            "content": json.dumps(tool_result, default=str),
                        })

                    # Continue loop — LLM may want to call more tools
                    continue

                # Handle text response (no tool calls = done)
                if reply.content:
                    # Check for handoff instruction
                    is_handoff = self._detect_handoff(reply.content)

                    msg_type = "handoff" if is_handoff else "text"
                    metadata = (
                        self._parse_handoff(reply.content) if is_handoff else None
                    )

                    bot_msg = await self._save_message(
                        db, conversation_id, "bot", bot_id,
                        reply.content, message_type=msg_type, metadata=metadata,
                    )
                    responses.append(bot_msg)

                    # Store in memory
                    await self.memory.store_message(
                        bot_id, conversation_id, "assistant", reply.content
                    )

                if not reply.content:
                    responses.append(await self._save_message(db, conversation_id, "system", None, "The model returned no visible answer. Increase response length or lower thinking effort, then try again.", message_type="status_update"))
                # Done — exit the loop
                break
            else:
                responses.append(await self._save_message(db, conversation_id, "system", None, "Agent iteration limit reached before completion.", message_type="status_update"))

        except Exception as e:
            logger.exception(f"Agent loop error for bot '{bot.name}': {e}")
            bot.status = "error"
            reason = str(e).lower()
            explanation = "Model execution failed. Check the configured provider and private server logs."
            if 'restrictedmodelserror' in reason or 'free tier users' in reason:
                explanation = "Vercel AI Gateway requires paid credits for this model. Add gateway credits in your Vercel team, then retry. Your ChatGPT subscription does not include API usage."
            elif 'insufficient' in reason or 'credit' in reason or 'quota' in reason:
                explanation = "The model provider reports a credit or quota limit. Check your gateway/provider billing and retry."
            error_msg = await self._save_message(
                db, conversation_id, "system", None,
                explanation, message_type="status_update",
            )
            responses.append(error_msg)
        else:
            bot.status = "idle"
        finally:
            await db.commit()
            await self._broadcast_status(bot_id, bot.status)

        return responses

    def _build_system_prompt(self, bot: Bot) -> str:
        """Build a complete system prompt for a bot."""
        base = bot.system_prompt or f"You are {bot.name}, a helpful AI assistant."
        tools_desc = ""
        if bot.tools_enabled:
            tools_desc = (
                "\n\nYou have access to the following tools:\n"
                + "\n".join(f"- {t}" for t in bot.tools_enabled)
                + "\n\nUse them when needed to complete tasks. "
                "Always aim for end-to-end task completion — don't just describe "
                "what to do, actually do it using your tools."
            )

        handoff_desc = (
            "\n\nIf a task is outside your expertise, you can hand it off to "
            "another bot by including HANDOFF[bot_name: reason] in your response."
        )

        return f"{base}\n\nYour role: {bot.role}{tools_desc}{handoff_desc}"

    def _detect_handoff(self, content: str) -> bool:
        """Detect if a message contains a handoff instruction."""
        return "HANDOFF[" in content

    def _parse_handoff(self, content: str) -> dict:
        """Parse handoff metadata from message content."""
        try:
            start = content.index("HANDOFF[") + 8
            end = content.index("]", start)
            handoff_str = content[start:end]
            parts = handoff_str.split(":", 1)
            return {
                "target_bot_name": parts[0].strip(),
                "context": parts[1].strip() if len(parts) > 1 else "",
            }
        except (ValueError, IndexError):
            return {}

    async def _save_message(
        self, db, conversation_id, sender_type, sender_bot_id,
        content, message_type="text", metadata=None,
    ) -> dict:
        """Save a message to the database and broadcast it."""
        if getattr(self, "internal_activity", False) or message_type in {"tool_call", "tool_result"}:
            metadata = {**(metadata or {}), "internal": True}
        msg = Message(
            id=str(uuid.uuid4()),
            conversation_id=conversation_id,
            sender_type=sender_type,
            sender_bot_id=sender_bot_id,
            content=content,
            message_type=message_type,
            metadata_json=metadata,
            created_at=datetime.now(timezone.utc).replace(tzinfo=None),
        )
        db.add(msg)
        await db.commit()

        msg_dict = {
            "id": msg.id,
            "conversation_id": conversation_id,
            "sender_type": sender_type,
            "sender_bot_id": sender_bot_id,
            "content": content,
            "message_type": message_type,
            "metadata": {**(metadata or {}), "attachments": [{"name": a["name"], "mime": a["mime"]} for a in (metadata or {}).get("attachments", [])]} if metadata and "attachments" in metadata else metadata,
            "created_at": msg.created_at.isoformat(),
        }

        # Broadcast via Redis pub/sub
        await self._broadcast_message(conversation_id, msg_dict)
        return msg_dict

    async def _broadcast_message(self, conversation_id: str, message: dict):
        """Broadcast a message to WebSocket clients via Redis pub/sub."""
        if self.redis:
            try:
                await self.redis.publish(
                    f"conversation:{conversation_id}",
                    json.dumps({
                        "type": "new_message",
                        "payload": message,
                    }),
                )
            except Exception as e:
                logger.warning(f"Failed to broadcast message: {e}")

    async def _broadcast_status(self, bot_id: str, status: str):
        """Broadcast a bot status change."""
        if self.redis:
            try:
                await self.redis.publish(
                    "bot_status",
                    json.dumps({
                        "type": "bot_status",
                        "payload": {"bot_id": bot_id, "status": status},
                    }),
                )
            except Exception as e:
                logger.warning(f"Failed to broadcast status: {e}")
